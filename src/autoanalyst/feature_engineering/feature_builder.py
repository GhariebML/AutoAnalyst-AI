class DatetimeColumnDetector:
    """Detects columns that represent dates or timestamps."""

    def __init__(self, parse_sample_size: int = 100, min_parse_ratio: float = 0.9) -> None:
        self._parse_sample_size = parse_sample_size
        self._min_parse_ratio = min_parse_ratio

    def _is_parseable_as_datetime(self, series: pd.Series) -> bool:
        non_null_values = series.dropna()
        if non_null_values.empty:
            return False

        sample = non_null_values.sample(
            n=min(self._parse_sample_size, len(non_null_values)),
            random_state=42,
        )
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", UserWarning)
            parsed = pd.to_datetime(sample, errors="coerce")
        success_ratio = parsed.notna().mean()
        return bool(success_ratio >= self._min_parse_ratio)

    def detect(self, data_frame: pd.DataFrame) -> list[str]:
        detected_columns: list[str] = []

        for column in data_frame.columns:
            series = data_frame[column]

            if pd.api.types.is_datetime64_any_dtype(series):
                detected_columns.append(column)
                continue

            is_textual_dtype = pd.api.types.is_object_dtype(
                series
            ) or pd.api.types.is_string_dtype(series)
            if is_textual_dtype and self._is_parseable_as_datetime(series):
                detected_columns.append(column)

        return detected_columns


