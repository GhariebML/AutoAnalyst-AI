class FeatureBuilder:
    """
    Builds derived features from raw tabular data, in a fully generic and
    dataset-agnostic manner.
    """

    def __init__(
        self,
        rare_category_threshold: float = 0.01,
        rare_category_label: str = "rare",
        rare_category_min_unique: int = 10,
        drop_original_datetime_columns: bool = True,
    ) -> None:
        self._rare_category_threshold = rare_category_threshold
        self._rare_category_label = rare_category_label
        self._rare_category_min_unique = rare_category_min_unique
        self._drop_original_datetime_columns = drop_original_datetime_columns
        self._datetime_detector = DatetimeColumnDetector()

    def detect_datetime_columns(self, data_frame: pd.DataFrame) -> list[str]:
        return self._datetime_detector.detect(data_frame)

    def _to_datetime(self, series: pd.Series) -> pd.Series:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", UserWarning)
            return pd.to_datetime(series, errors="coerce")

    def extract_year(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        data_frame = data_frame.copy()
        data_frame[f"{column}_year"] = self._to_datetime(data_frame[column]).dt.year
        return data_frame

    def extract_month(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        data_frame = data_frame.copy()
        data_frame[f"{column}_month"] = self._to_datetime(data_frame[column]).dt.month
        return data_frame

    def extract_day(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        data_frame = data_frame.copy()
        data_frame[f"{column}_day"] = self._to_datetime(data_frame[column]).dt.day
        return data_frame

    def extract_day_of_week(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        data_frame = data_frame.copy()
        data_frame[f"{column}_day_of_week"] = self._to_datetime(
            data_frame[column]
        ).dt.dayofweek
        return data_frame

    def extract_quarter(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        data_frame = data_frame.copy()
        data_frame[f"{column}_quarter"] = self._to_datetime(data_frame[column]).dt.quarter
        return data_frame

    def extract_is_weekend(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        data_frame = data_frame.copy()
        day_of_week = self._to_datetime(data_frame[column]).dt.dayofweek
        data_frame[f"{column}_is_weekend"] = day_of_week.isin([5, 6])
        return data_frame

    def extract_datetime_features(
        self, data_frame: pd.DataFrame, column: str
    ) -> pd.DataFrame:
        if column not in data_frame.columns:
            raise KeyError(f"Column '{column}' does not exist in the provided DataFrame.")

        data_frame = self.extract_year(data_frame, column)
        data_frame = self.extract_month(data_frame, column)
        data_frame = self.extract_day(data_frame, column)
        data_frame = self.extract_day_of_week(data_frame, column)
        data_frame = self.extract_quarter(data_frame, column)
        data_frame = self.extract_is_weekend(data_frame, column)

        if self._drop_original_datetime_columns:
            data_frame = data_frame.drop(columns=[column])

        logger.info("Extracted calendar features from datetime column '%s'.", column)
        return data_frame

    def group_rare_categories(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        if column not in data_frame.columns:
            raise KeyError(f"Column '{column}' does not exist in the provided DataFrame.")

        unique_count = data_frame[column].nunique(dropna=True)
        if unique_count < self._rare_category_min_unique:
            return data_frame
