class OutlierHandler:
    """Detects and handles outliers in numerical columns using the IQR rule."""

    def __init__(self, config: PreprocessingConfig) -> None:
        self._config = config
        self._type_detector = ColumnTypeDetector(config)

    def compute_iqr_bounds(
        self, data_frame: pd.DataFrame, column: str
    ) -> tuple[float, float]:
        first_quartile = data_frame[column].quantile(0.25)
        third_quartile = data_frame[column].quantile(0.75)
        interquartile_range = third_quartile - first_quartile
        multiplier = self._config.outlier_iqr_multiplier
        lower_bound = first_quartile - multiplier * interquartile_range
        upper_bound = third_quartile + multiplier * interquartile_range
        return lower_bound, upper_bound

    def detect_outliers(
        self, data_frame: pd.DataFrame, column: str
    ) -> pd.Series:
        lower_bound, upper_bound = self.compute_iqr_bounds(data_frame, column)
        return (data_frame[column] < lower_bound) | (data_frame[column] > upper_bound)

    def remove_outliers(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        mask = self.detect_outliers(data_frame, column)
        return data_frame.loc[~mask].reset_index(drop=True)

    def cap_outliers(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        lower_bound, upper_bound = self.compute_iqr_bounds(data_frame, column)
        data_frame = data_frame.copy()
        data_frame[column] = data_frame[column].clip(lower=lower_bound, upper=upper_bound)
        return data_frame

    def flag_outliers(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        data_frame = data_frame.copy()
        flag_column = f"{column}_is_outlier"
        data_frame[flag_column] = self.detect_outliers(data_frame, column)
        return data_frame

    def handle_outliers(
        self,
        data_frame: pd.DataFrame,
        strategy: Optional[OutlierStrategy] = None,
        columns: Optional[list[str]] = None,
    ) -> pd.DataFrame:
        strategy = strategy or self._config.outlier_strategy
        target_columns = columns or self._type_detector.detect_numerical_columns(
            data_frame
        )
        data_frame = data_frame.copy()

        for column in target_columns:
            outlier_count = int(self.detect_outliers(data_frame, column).sum())
            if outlier_count == 0:
                continue

            logger.info(
                "Found %d outlier(s) in column '%s'. Applying strategy '%s'.",
                outlier_count,
                column,
                strategy.value,
            )
            if strategy == OutlierStrategy.REMOVE:
                data_frame = self.remove_outliers(data_frame, column)
            elif strategy == OutlierStrategy.CAP:
                data_frame = self.cap_outliers(data_frame, column)
            elif strategy == OutlierStrategy.FLAG:
                data_frame = self.flag_outliers(data_frame, column)
            else:
                raise ConfigurationError(f"Unsupported outlier strategy: {strategy}")

        return data_frame.reset_index(drop=True)


