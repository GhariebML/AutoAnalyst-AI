class ColumnTypeDetector:
    """Detects numerical, categorical, datetime and boolean columns."""

    def __init__(self, config: PreprocessingConfig) -> None:
        self._config = config

    def _usable_columns(self, data_frame: pd.DataFrame) -> list[str]:
        return [
            column
            for column in data_frame.columns
            if column not in self._config.columns_to_exclude
        ]

    def detect_boolean_columns(self, data_frame: pd.DataFrame) -> list[str]:
        return [
            column
            for column in self._usable_columns(data_frame)
            if pd.api.types.is_bool_dtype(data_frame[column])
        ]

    def _is_string_datetime_column(self, series: pd.Series) -> bool:
        is_textual_dtype = pd.api.types.is_object_dtype(series) or pd.api.types.is_string_dtype(
            series
        )
        if not is_textual_dtype:
            return False

        non_null_values = series.dropna()
        if non_null_values.empty:
            return False

        sample_size = min(50, len(non_null_values))
        sample = non_null_values.sample(n=sample_size, random_state=42)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", UserWarning)
            parsed = pd.to_datetime(sample, errors="coerce")
        return bool(parsed.notna().mean() >= 0.9)

    def detect_datetime_columns(self, data_frame: pd.DataFrame) -> list[str]:
        detected: list[str] = []
        for column in self._usable_columns(data_frame):
            series = data_frame[column]
            if pd.api.types.is_datetime64_any_dtype(series):
                detected.append(column)
            elif self._is_string_datetime_column(series):
                detected.append(column)
        return detected

    def detect_numerical_columns(self, data_frame: pd.DataFrame) -> list[str]:
        boolean_columns = set(self.detect_boolean_columns(data_frame))
        return [
            column
            for column in self._usable_columns(data_frame)
            if pd.api.types.is_numeric_dtype(data_frame[column])
            and column not in boolean_columns
        ]

    def detect_categorical_columns(self, data_frame: pd.DataFrame) -> list[str]:
        numerical_columns = set(self.detect_numerical_columns(data_frame))
        datetime_columns = set(self.detect_datetime_columns(data_frame))
        boolean_columns = set(self.detect_boolean_columns(data_frame))
        excluded = numerical_columns | datetime_columns | boolean_columns
        return [
            column
            for column in self._usable_columns(data_frame)
            if column not in excluded
        ]


