class DataCleaner:
    """Performs structural cleaning operations on a DataFrame."""

    def remove_duplicate_rows(self, data_frame: pd.DataFrame) -> pd.DataFrame:
        duplicate_count = int(data_frame.duplicated().sum())
        if duplicate_count > 0:
            logger.info("Removing %d duplicate row(s).", duplicate_count)
            data_frame = data_frame.drop_duplicates().reset_index(drop=True)
        else:
            logger.info("No duplicate rows found.")
        return data_frame

    def standardize_column_names(self, data_frame: pd.DataFrame) -> pd.DataFrame:
        new_columns = (
            data_frame.columns.astype(str)
            .str.strip()
            .str.lower()
            .str.replace(r"[^0-9a-zA-Z]+", "_", regex=True)
            .str.strip("_")
        )
        data_frame = data_frame.copy()
        data_frame.columns = new_columns
        logger.info("Standardized column names.")
        return data_frame

    def standardize_string_values(self, data_frame: pd.DataFrame) -> pd.DataFrame:
        data_frame = data_frame.copy()
        textual_columns = [
            column
            for column in data_frame.columns
            if pd.api.types.is_object_dtype(data_frame[column])
            or pd.api.types.is_string_dtype(data_frame[column])
        ]
        for column in textual_columns:
            data_frame[column] = (
                data_frame[column]
                .apply(lambda value: value.strip() if isinstance(value, str) else value)
            )
        logger.info("Standardized string values in %d column(s).", len(textual_columns))
        return data_frame

    def remove_empty_rows(self, data_frame: pd.DataFrame) -> pd.DataFrame:
        before = data_frame.shape[0]
        data_frame = data_frame.dropna(axis=0, how="all").reset_index(drop=True)
        removed = before - data_frame.shape[0]
        if removed > 0:
            logger.info("Removed %d fully empty row(s).", removed)
        return data_frame

    def remove_empty_columns(self, data_frame: pd.DataFrame) -> pd.DataFrame:
        before_columns = set(data_frame.columns)
        data_frame = data_frame.dropna(axis=1, how="all")
        removed = before_columns - set(data_frame.columns)
        if removed:
            logger.info("Removed fully empty column(s): %s", sorted(removed))
        return data_frame

    def clean(self, data_frame: pd.DataFrame) -> pd.DataFrame:
        data_frame = self.standardize_column_names(data_frame)
        data_frame = self.remove_empty_rows(data_frame)
        data_frame = self.remove_empty_columns(data_frame)
        data_frame = self.remove_duplicate_rows(data_frame)
        data_frame = self.standardize_string_values(data_frame)
        return data_frame


