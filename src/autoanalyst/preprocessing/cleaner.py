class CategoricalEncoder:
    """Encodes categorical columns, safely handling high cardinality."""

    def __init__(self, config: PreprocessingConfig) -> None:
        self._config = config
        self._type_detector = ColumnTypeDetector(config)

    def detect_categorical_columns(self, data_frame: pd.DataFrame) -> list[str]:
        return self._type_detector.detect_categorical_columns(data_frame)

    def _group_high_cardinality_values(
        self, series: pd.Series, max_categories: int
    ) -> pd.Series:
        top_categories = series.value_counts().index[:max_categories]
        return series.where(series.isin(top_categories), other="other")

    def one_hot_encode(
        self, data_frame: pd.DataFrame, columns: Optional[list[str]] = None
    ) -> pd.DataFrame:
        data_frame = data_frame.copy()
        target_columns = columns or self.detect_categorical_columns(data_frame)
        if not target_columns:
            logger.info("No categorical columns to encode.")
            return data_frame

        for column in target_columns:
            unique_count = data_frame[column].nunique(dropna=True)
            if unique_count > self._config.one_hot_max_categories:
                logger.warning(
                    "Column '%s' has high cardinality (%d). "
                    "Grouping rare categories before encoding.",
                    column,
                    unique_count,
                )
                data_frame[column] = self._group_high_cardinality_values(
                    data_frame[column], self._config.one_hot_max_categories
                )

        encoded = pd.get_dummies(
            data_frame, columns=target_columns, prefix=target_columns, dummy_na=False
        )
        logger.info("One-hot encoded column(s): %s", target_columns)
        return encoded


