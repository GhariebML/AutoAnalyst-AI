class FeatureScaler:
    """Scales numerical columns using configurable scikit-learn scalers."""

    _SCALER_FACTORY = {
        ScalingStrategy.STANDARD: StandardScaler,
        ScalingStrategy.MIN_MAX: MinMaxScaler,
        ScalingStrategy.ROBUST: RobustScaler,
    }

    def __init__(self, config: PreprocessingConfig) -> None:
        self._config = config
        self._type_detector = ColumnTypeDetector(config)

    def scale(
        self,
        data_frame: pd.DataFrame,
        strategy: Optional[ScalingStrategy] = None,
        columns: Optional[list[str]] = None,
    ) -> pd.DataFrame:
        strategy = strategy or self._config.scaling_strategy
        target_columns = columns or self._type_detector.detect_numerical_columns(
            data_frame
        )
        if not target_columns:
            logger.info("No numerical columns to scale.")
            return data_frame

        scaler_class = self._SCALER_FACTORY.get(strategy)
        if scaler_class is None:
            raise ConfigurationError(f"Unsupported scaling strategy: {strategy}")

        data_frame = data_frame.copy()
        scaler = scaler_class()
        data_frame[target_columns] = scaler.fit_transform(data_frame[target_columns])
        logger.info(
            "Scaled column(s) %s using strategy '%s'.", target_columns, strategy.value
        )
        return data_frame


