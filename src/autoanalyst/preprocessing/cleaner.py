class Normalizer:
    """Applies variance-stabilizing transformations to skewed numerical data."""

    def __init__(self, config: PreprocessingConfig) -> None:
        self._config = config
        self._type_detector = ColumnTypeDetector(config)

    def log_transform(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        data_frame = data_frame.copy()
        minimum_value = data_frame[column].min()
        shift = abs(minimum_value) + 1.0 if minimum_value < 0 else 0.0
        data_frame[column] = np.log1p(data_frame[column] + shift)
        return data_frame

    def sqrt_transform(self, data_frame: pd.DataFrame, column: str) -> pd.DataFrame:
        data_frame = data_frame.copy()
        minimum_value = data_frame[column].min()
        shift = abs(minimum_value) if minimum_value < 0 else 0.0
        data_frame[column] = np.sqrt(data_frame[column] + shift)
        return data_frame

    def normalize(
        self,
        data_frame: pd.DataFrame,
        strategy: Optional[NormalizationStrategy] = None,
        columns: Optional[list[str]] = None,
    ) -> pd.DataFrame:
        strategy = strategy or self._config.normalization_strategy
        if strategy is None:
            logger.info("Normalization disabled by configuration.")
            return data_frame

        target_columns = columns or self._type_detector.detect_numerical_columns(
            data_frame
        )
        data_frame = data_frame.copy()

        for column in target_columns:
            skewness = data_frame[column].skew()
            if abs(skewness) <= self._config.skewness_threshold:
                continue

            logger.info(
                "Normalizing skewed column '%s' (skew=%.3f) using '%s'.",
                column,
                skewness,
                strategy.value,
            )
            if strategy == NormalizationStrategy.LOG:
                data_frame = self.log_transform(data_frame, column)
            elif strategy == NormalizationStrategy.SQRT:
                data_frame = self.sqrt_transform(data_frame, column)
            else:
                raise ConfigurationError(f"Unsupported normalization strategy: {strategy}")

        return data_frame


# ======================================================================
# Preprocessing pipeline orchestrator
# ======================================================================

class PreprocessingPipeline:
    """
    Orchestrates the complete, generic preprocessing pipeline for any
    tabular dataset.
    """

    def __init__(self, config: Optional[PreprocessingConfig] = None) -> None:
        self._config = config or PreprocessingConfig()
        self._validator = DataValidator(self._config)
        self._cleaner = DataCleaner()
        self._missing_value_handler = MissingValueHandler(self._config)
        self._outlier_handler = OutlierHandler(self._config)
        self._encoder = CategoricalEncoder(self._config)
        self._scaler = FeatureScaler(self._config)
        self._normalizer = Normalizer(self._config)
        self._feature_builder = FeatureBuilder(
            rare_category_threshold=self._config.rare_category_threshold
        )

    def run(self, data_frame: pd.DataFrame) -> pd.DataFrame:
        logger.info("Starting preprocessing pipeline. Input shape: %s", data_frame.shape)

        self._validator.run_initial_validation(data_frame)

        data_frame = self._cleaner.clean(data_frame)
        logger.info("Cleaning complete. Shape: %s", data_frame.shape)

        data_frame = self._missing_value_handler.handle_missing_values(data_frame)
        logger.info("Missing value handling complete. Shape: %s", data_frame.shape)

        data_frame = self._outlier_handler.handle_outliers(data_frame)
        logger.info("Outlier handling complete. Shape: %s", data_frame.shape)

        data_frame = self._encoder.one_hot_encode(data_frame)
        logger.info("Encoding complete. Shape: %s", data_frame.shape)

        data_frame = self._scaler.scale(data_frame)
        logger.info("Scaling complete. Shape: %s", data_frame.shape)

        data_frame = self._normalizer.normalize(data_frame)
        logger.info("Normalization complete. Shape: %s", data_frame.shape)

        data_frame = self._feature_builder.build_features(data_frame)
        logger.info("Feature engineering complete. Shape: %s", data_frame.shape)

        self._validator.run_final_validation(data_frame)
        logger.info("Preprocessing pipeline finished. Output shape: %s", data_frame.shape)

        return data_frame


def build_ml_ready_dataset(
    data_frame: pd.DataFrame, config: Optional[PreprocessingConfig] = None
) -> pd.DataFrame:
    pipeline = PreprocessingPipeline(config=config)
    return pipeline.run(data_frame)
