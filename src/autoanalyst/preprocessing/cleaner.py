class MissingValueHandler:
    """Analyzes and resolves missing values in a DataFrame."""

    def __init__(self, config: PreprocessingConfig) -> None:
        self._config = config
        self._type_detector = ColumnTypeDetector(config)

    def analyze_missing_values(self, data_frame: pd.DataFrame) -> pd.DataFrame:
        missing_count = data_frame.isnull().sum()
        missing_percentage = missing_count / len(data_frame)
        summary = pd.DataFrame(
            {
                "missing_count": missing_count,
                "missing_percentage": missing_percentage,
            }
        )
        summary = summary[summary["missing_count"] > 0]
        return summary.sort_values("missing_percentage", ascending=False)

    def _impute_numerical(
        self, data_frame: pd.DataFrame, column: str, strategy: ImputationStrategy
    ) -> None:
        if strategy == ImputationStrategy.MEAN:
            fill_value = data_frame[column].mean()
        elif strategy == ImputationStrategy.MEDIAN:
            fill_value = data_frame[column].median()
        else:
            raise ConfigurationError(
                f"Strategy '{strategy}' is not valid for numerical imputation."
            )
        data_frame[column] = data_frame[column].fillna(fill_value)

    def _impute_categorical(self, data_frame: pd.DataFrame, column: str) -> None:
        mode_values = data_frame[column].mode(dropna=True)
        fill_value = mode_values.iloc[0] if not mode_values.empty else "unknown"
        data_frame[column] = data_frame[column].fillna(fill_value)

    def handle_missing_values(self, data_frame: pd.DataFrame) -> pd.DataFrame:
        data_frame = data_frame.copy()
        summary = self.analyze_missing_values(data_frame)
        if summary.empty:
            logger.info("No missing values found.")
            return data_frame

        numerical_columns = set(self._type_detector.detect_numerical_columns(data_frame))
        columns_to_drop: list[str] = []

        for column, row in summary.iterrows():
            missing_fraction = row["missing_percentage"]

            if missing_fraction >= self._config.missing_value_threshold_drop_column:
                columns_to_drop.append(str(column))
                continue

            if missing_fraction < self._config.missing_value_threshold_drop_row:
                data_frame = data_frame.dropna(subset=[column])
                logger.info("Dropped rows with missing values in '%s'.", column)
                continue

            if column in numerical_columns:
                skewness = data_frame[column].skew()
                strategy = (
                    ImputationStrategy.MEDIAN
                    if abs(skewness) > self._config.skewness_threshold
                    else ImputationStrategy.MEAN
                )
                self._impute_numerical(data_frame, str(column), strategy)
                logger.info(
                    "Imputed numerical column '%s' using strategy '%s'.",
                    column,
                    strategy.value,
                )
            else:
                self._impute_categorical(data_frame, str(column))
                logger.info("Imputed categorical column '%s' using mode.", column)

        if columns_to_drop:
            data_frame = data_frame.drop(columns=columns_to_drop)
            logger.info(
                "Dropped column(s) exceeding missing threshold: %s",
                columns_to_drop,
            )

        return data_frame.reset_index(drop=True)


