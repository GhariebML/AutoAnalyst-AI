class DataValidator:
    """Performs structural and quality validation on a DataFrame."""

    def __init__(self, config: PreprocessingConfig) -> None:
        self._config = config
        self._type_detector = ColumnTypeDetector(config)

    def validate_not_empty(self, data_frame: pd.DataFrame) -> None:
        if data_frame.shape[0] == 0 or data_frame.shape[1] == 0:
            raise EmptyDatasetError(
                f"Dataset is empty: shape={data_frame.shape}."
            )

    def validate_unique_columns(self, data_frame: pd.DataFrame) -> None:
        duplicated = data_frame.columns[data_frame.columns.duplicated()].tolist()
        if duplicated:
            raise DuplicateColumnError(
                f"Duplicate column names found: {duplicated}."
            )

    def check_missing_values(self, data_frame: pd.DataFrame) -> pd.Series:
        missing_counts = data_frame.isnull().sum()
        return missing_counts[missing_counts > 0]

    def validate_datatypes(self, data_frame: pd.DataFrame) -> None:
        supported_kinds = {"b", "i", "u", "f", "c", "O", "M", "m"}
        invalid_columns = [
            column
            for column in data_frame.columns
            if data_frame[column].dtype.kind not in supported_kinds
        ]
        if invalid_columns:
            raise InvalidDatatypeError(
                f"Unsupported dtypes found in columns: {invalid_columns}."
            )

    def validate_datetime_columns(
        self, data_frame: pd.DataFrame, datetime_columns: Optional[list[str]] = None
    ) -> None:
        columns_to_check = (
            datetime_columns
            if datetime_columns is not None
            else self._type_detector.detect_datetime_columns(data_frame)
        )
        for column in columns_to_check:
            if column not in data_frame.columns:
                continue
            try:
                with warnings.catch_warnings():
                    warnings.simplefilter("ignore", UserWarning)
                    pd.to_datetime(data_frame[column], errors="raise")
            except (ValueError, TypeError) as error:
                raise InvalidDatetimeError(
                    f"Column '{column}' cannot be parsed as datetime: {error}"
                ) from error

    def validate_infinite_values(self, data_frame: pd.DataFrame) -> None:
        numerical_columns = self._type_detector.detect_numerical_columns(data_frame)
        if not numerical_columns:
            return
        numerical_data = data_frame[numerical_columns]
        has_infinite = np.isinf(numerical_data.to_numpy(dtype=float, na_value=0.0)).any()
        if has_infinite:
            affected = [
                column
                for column in numerical_columns
                if np.isinf(data_frame[column].to_numpy(dtype=float)).any()
            ]
            raise InfiniteValueError(
                f"Infinite values detected in columns: {affected}."
            )

    def detect_constant_columns(self, data_frame: pd.DataFrame) -> list[str]:
        return [
            column
            for column in data_frame.columns
            if data_frame[column].nunique(dropna=True)
            <= self._config.constant_column_unique_threshold
        ]

    def detect_high_cardinality_columns(self, data_frame: pd.DataFrame) -> list[str]:
        categorical_columns = self._type_detector.detect_categorical_columns(
            data_frame
        )
        return [
            column
            for column in categorical_columns
            if data_frame[column].nunique(dropna=True)
            > self._config.high_cardinality_threshold
        ]

    def run_initial_validation(self, data_frame: pd.DataFrame) -> None:
        logger.info("Running initial data validation.")
        self.validate_not_empty(data_frame)
        self.validate_unique_columns(data_frame)
        self.validate_datatypes(data_frame)

        missing_summary = self.check_missing_values(data_frame)
        if not missing_summary.empty:
            logger.info(
                "Missing values detected in %d column(s): %s",
                len(missing_summary),
                missing_summary.to_dict(),
            )

        constant_columns = self.detect_constant_columns(data_frame)
        if constant_columns:
            logger.warning("Constant columns detected: %s", constant_columns)

        high_cardinality_columns = self.detect_high_cardinality_columns(data_frame)
        if high_cardinality_columns:
            logger.warning(
                "High-cardinality columns detected: %s", high_cardinality_columns
            )

    def run_final_validation(self, data_frame: pd.DataFrame) -> None:
        logger.info("Running final data validation.")
        self.validate_not_empty(data_frame)
        self.validate_unique_columns(data_frame)
        self.validate_infinite_values(data_frame)

        remaining_missing = self.check_missing_values(data_frame)
        if not remaining_missing.empty:
            raise DataPreprocessingError(
                f"Final dataset still contains missing values: "
                f"{remaining_missing.to_dict()}."
            )


