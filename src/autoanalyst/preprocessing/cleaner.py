def remove_duplicates(df: pd.DataFrame) -> pd.DataFrame:
    """
    Remove duplicate rows from the DataFrame.

    Args:
        df: Input DataFrame.

    Returns:
        DataFrame with duplicate rows removed.
    """
    return df.drop_duplicates().reset_index(drop=True)


def handle_missing_values(df: pd.DataFrame, strategy: str = "median") -> pd.DataFrame:
    """
    Handle missing values using the specified strategy.

    Strategies:
        - 'mean': Fill numerical columns with mean, categorical with mode.
        - 'median': Fill numerical columns with median, categorical with mode.
        - 'mode': Fill all columns with mode.
        - 'drop': Drop rows containing any missing value.

    Args:
        df: Input DataFrame.
        strategy: Imputation strategy ('mean', 'median', 'mode', 'drop').

    Returns:
        DataFrame with missing values handled.

    Raises:
        ValueError: If an unsupported strategy is provided.
    """
    if strategy == "drop":
        return df.dropna().reset_index(drop=True)

    df_copy = df.copy()

    # Handle numerical columns
    numeric_cols = df_copy.select_dtypes(include=["number"]).columns
    for col in numeric_cols:
        if strategy == "mean":
            fill_val = df_copy[col].mean()
        elif strategy == "median":
            fill_val = df_copy[col].median()
        elif strategy == "mode":
            mode_vals = df_copy[col].mode()
            fill_val = mode_vals[0] if not mode_vals.empty else df_copy[col].median()
        else:
            raise ValueError(
                f"Unsupported strategy: '{strategy}'. "
                f"Choose from: mean, median, mode, drop"
            )
        df_copy[col] = df_copy[col].fillna(fill_val)

    # Handle categorical/text columns (always use mode)
    cat_cols = df_copy.select_dtypes(include=["object", "category", "string"]).columns
    for col in cat_cols:
        mode_vals = df_copy[col].mode()
        fill_val = mode_vals[0] if not mode_vals.empty else "unknown"
        df_copy[col] = df_copy[col].fillna(fill_val)

    return df_copy.reset_index(drop=True)


